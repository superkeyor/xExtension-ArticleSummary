function configureSummarizeButtons() {
  document.getElementById('global').addEventListener('click', function (e) {
    for (var target = e.target; target && target != this; target = target.parentNode) {
      
      if (target.matches('.flux_header')) {
        target.nextElementSibling.querySelectorAll('.oai-summary-btn').forEach(btn => btn.innerHTML = '✨Summarize');
      }

      if (target.matches('.oai-summary-btn')) {
        e.preventDefault();
        e.stopPropagation();
        if (target.dataset.request) {
          summarizeButtonClick(target);
        }
        break;
      }
    }
  }, false);
}

function setOaiState(container, statusType, statusMsg, summaryText) {
  const button = container.querySelector('.oai-summary-btn');
  const content = container.querySelector('.oai-summary-content');
  const wrap = container.closest('.oai-summary-wrap');

  if (!button || !content || !wrap) {
    return;
  }

  if (statusType === 1) {
    container.classList.add('oai-loading');
    container.classList.remove('oai-error');
    content.innerHTML = statusMsg;
    content.style.display = 'block';
    const savedSummary = wrap.querySelector('.oai-summary-block');
    if (savedSummary) {
      savedSummary.style.display = 'none';
    }
    button.disabled = true;
    return;
  }

  if (statusType === 2) {
    container.classList.remove('oai-loading');
    container.classList.add('oai-error');
    content.innerHTML = statusMsg;
    content.style.display = 'block';
    const savedSummary = wrap.querySelector('.oai-summary-block');
    if (savedSummary) {
      savedSummary.style.display = 'none';
    }
    button.disabled = false;
    return;
  }

  container.classList.remove('oai-loading');
  container.classList.remove('oai-error');
  button.disabled = false;

  if (summaryText) {
    const article = container.closest('.flux_content');
    let summaryBlock = wrap.querySelector('.oai-summary-block');

    if (!summaryBlock) {
      summaryBlock = document.createElement('div');
      summaryBlock.className = 'oai-summary-block';
      wrap.appendChild(summaryBlock);
    }

    let summaryContent = summaryBlock.querySelector('.oai-summary-content');
    if (!summaryContent) {
      summaryContent = document.createElement('div');
      summaryContent.className = 'oai-summary-content';
      summaryBlock.appendChild(summaryContent);
    }

    let header = summaryBlock.querySelector('.oai-summary-header');
    if (!header) {
      header = document.createElement('h3');
      header.className = 'oai-summary-header';
      header.textContent = '✨ AI Summary';
      summaryBlock.insertBefore(header, summaryContent);
    }

    const rendered = marked.parse(summaryText.replace(/^<h3[^>]*>.*?✨ AI Summary.*?<\/h3>\s*/is, '')).replace(/(?:\r\n|\r|\n)(?![\s]*<(?:ul|li|\/div|\/ul|\/li)>)(?![\s]*$)/g, '<br>');
    summaryContent.innerHTML = rendered;
    content.innerHTML = '';
    content.style.display = 'none';
    summaryBlock.style.display = 'block';
    container.dataset.lastSummary = summaryText;
    summaryBlock.dataset.lastSummary = summaryText;

    if (article) {
      article.querySelectorAll('.oai-summary-block').forEach(block => {
        if (block !== summaryBlock && block.closest('.oai-summary-wrap') !== wrap) {
          block.remove();
        }
      });
    }
  } else if (statusMsg === 'finish') {
    content.innerHTML = '';
    content.style.display = 'none';
    const savedSummary = wrap.querySelector('.oai-summary-block');
    if (savedSummary) {
      savedSummary.style.display = 'block';
    }
  }
}

async function summarizeButtonClick(target) {
  var container = target.parentNode;

  if (container.classList.contains('oai-loading')) {
    return;
  }

  const article = container.closest('.flux_content');
  if (article) {
    article.querySelectorAll('.oai-summary-block').forEach(block => {
      if (block.closest('.oai-summary-wrap') !== container) {
        block.remove();
      }
    });
  }

  const wrap = container.closest('.oai-summary-wrap');
  if (wrap) {
    const existing = wrap.querySelector('.oai-summary-block');
    if (existing) {
      existing.style.display = 'none';
    }
  }

  setOaiState(container, 1, 'Loading...', null);

  // This is the PHP endpoint that receives the parameters
  var url = target.dataset.request;
  var data = {
    ajax: true,
    _csrf: context.csrf
  };

  try {
    const response = await retryWithBackoff(async () => {
      const response = await axios.post(url, data, {
        headers: {
          'Content-Type': 'application/json'
        }
      });
      if (!response.data?.response?.data) {
        throw new Error('Invalid response structure');
      }
      return response;
    });

    const xresp = response.data;

    if (response.status !== 200 || !xresp.response || !xresp.response.data) {
      throw new Error('Request Failed');
    }

    if (xresp.response.error) {
      setOaiState(container, 2, xresp.response.data, null);
    } else {
      const oaiParams = xresp.response.data;
      const oaiProvider = xresp.response.provider;
      if (oaiProvider === 'openai') {
        await sendOpenAIRequest(container, oaiParams);
      } else {
        await sendOllamaRequest(container, oaiParams);
      }
    }
  } catch (error) {
    console.error(error);
    setOaiState(container, 2, 'Request Failed', null);
  }
}

async function sendOpenAIRequest(container, oaiParams) {
  try {
    let body = JSON.parse(JSON.stringify(oaiParams));
    delete body['oai_url'];
    delete body['oai_key'];	  
    const response = await fetch(oaiParams.oai_url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${oaiParams.oai_key}`
      },
      body: JSON.stringify(body)
    });

    if (!response.ok) {
      throw new Error('Request Failed');
    }

    const reader = response.body.getReader();
    const decoder = new TextDecoder('utf-8');

    while (true) {
      const { done, value } = await reader.read();
      if (done) {
        setOaiState(container, 0, 'finish', null);
        // After completion, save summary to article
        await saveSummaryToArticle(container);
        break;
      }

      const chunk = decoder.decode(value, { stream: true });
      const text = JSON.parse(chunk)?.choices[0]?.message?.content || '';
      setOaiState(container, 0, null, text);
    }
  } catch (error) {
    console.error(error);
    setOaiState(container, 2, 'Request Failed', null);
  }
}


async function sendOllamaRequest(container, oaiParams){
  try {
    const response = await fetch(oaiParams.oai_url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${oaiParams.oai_key}`
      },
      body: JSON.stringify(oaiParams)
    });

    if (!response.ok) {
      throw new Error('Request Failed');
    }
  
    const reader = response.body.getReader();
    const decoder = new TextDecoder('utf-8');
    let text = '';
    let buffer = '';

    while (true) {
      const { done, value } = await reader.read();
      if (done) {
        setOaiState(container, 0, 'finish', null);
        // After completion, save summary to article
        await saveSummaryToArticle(container);
        break;
      }
      buffer += decoder.decode(value, { stream: true });
      // Try to process complete JSON objects from the buffer
      let endIndex;
      while ((endIndex = buffer.indexOf('\n')) !== -1) {
        const jsonString = buffer.slice(0, endIndex).trim();
        try {
          if (jsonString) {
            const json = JSON.parse(jsonString);
            text += json.response;
            setOaiState(container, 0, null, text);
          }
        } catch (e) {
          // If JSON parsing fails, output the error and keep the chunk for future attempts
          console.error('Error parsing JSON:', e, 'Chunk:', jsonString);
        }
        // Remove the processed part from the buffer
        buffer = buffer.slice(endIndex + 1); // +1 to remove the newline character
      }
    }
  } catch (error) {
    console.error(error);
    setOaiState(container, 2, 'Request Failed', null);
  }
}

async function saveSummaryToArticle(container) {
  const button = container.querySelector('.oai-summary-btn');
  const entryId = button.dataset.entryId;
  const summary = container.dataset.lastSummary;

  if (!entryId || !summary) {
    console.error('Missing entry ID or summary');
    return;
  }

  try {
    const response = await axios.post('?c=ArticleSummary&a=saveSummary', {
      id: entryId,
      summary: summary,
      ajax: true,
      _csrf: context.csrf
    }, {
      headers: {
        'Content-Type': 'application/json'
      }
    });

    if (response.data.status === 200 && response.data.inserted) {
      const button = container.querySelector('.oai-summary-btn');
      if (button) {
        button.style.display = '';
        button.disabled = false;
        button.textContent = '✨Summarize';
      }

      const article = container.closest('.flux_content');
      if (article) {
        article.querySelectorAll('.oai-summary-wrap').forEach(wrap => {
          if (wrap !== container.closest('.oai-summary-wrap')) {
            wrap.remove();
          }
        });
      }
    } else {
      setOaiState(container, 0, 'Summary generated (already in article)', null);
      setTimeout(() => {
        button.disabled = false;
      }, 2000);
    }
  } catch (error) {
    console.error('Error saving summary:', error);
    setOaiState(container, 2, 'Generated but failed to save to article', null);
  }
}

// Parse auto-generated summaries on page load (convert markdown to HTML)
function parseAutoGeneratedSummaries(retryCount = 0) {
  // Check if marked.js is loaded
  if (typeof marked === 'undefined') {
    if (retryCount >= 50) { // Stop after 5 seconds (50 * 100ms)
      console.error('marked.js failed to load after 5 seconds, giving up');
      return;
    }
    console.warn('marked.js not loaded yet, retrying... (' + (retryCount + 1) + '/50)');
    setTimeout(() => parseAutoGeneratedSummaries(retryCount + 1), 100);
    return;
  }
  
  const summaryBlocks = document.querySelectorAll('.oai-summary-block .oai-summary-content');
  
  summaryBlocks.forEach(content => {
    // Check if already parsed (contains HTML tags)
    if (content.innerHTML.includes('<p>') || content.innerHTML.includes('<li>')) {
      return; // Already parsed
    }
    
    // Parse markdown to HTML using marked.js (same as manual processing)
    const markdown = content.textContent;
    const parsed = marked.parse(markdown);
    // Replace newlines with <br>, except before certain HTML tags or at the end
    content.innerHTML = parsed.replace(/(?:\r\n|\r|\n)(?![\s]*<(?:ul|li|\/div|\/ul|\/li)>)(?![\s]*$)/g, '<br>');
  });
}

